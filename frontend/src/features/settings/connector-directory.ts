/** connectorName 在中文界面用目录里的中文名。英文界面沿用后端名字。 */
export function connectorName(provider: string, fallback: string, locale: string): string {
  if (!locale.startsWith("zh")) return fallback;
  return names[provider] || fallback;
}

/** resolvedAccess 在旧目录没有 access 字段时，仍认出已经能授权的几项。 */
export function resolvedAccess(provider: string, access: string): string {
  if (access) return access;
  if (provider === "gmail" || provider === "outlook" || provider === "gcal" || provider === "slack") return "oauth";
  if (provider === "github" || provider === "feishu") return "source";
  return "mcp";
}

/** connectorBlurb 返回这一项的一句说明。没有专句时用接入方式的默认句。 */
export function connectorBlurb(provider: string, locale: string): string {
  const row = blurbs[provider];
  if (!row) return "";
  return locale.startsWith("zh") ? row.zh : row.en;
}
