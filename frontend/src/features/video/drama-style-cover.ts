/** 转义要写进 SVG 文本的字符。value 把 &、<、>、引号换成实体。 */
function escapeXml(value: string) {
  return value.replace(/[&<>"']/g, /** ch 换成对应实体，不在表里就原样返回。 */ (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" }[ch] || ch));
}

/** 用风格值的字符算出一组色板和纹样。key 用每个字符的编码滚动哈希，取色相、角标前 10 个字符和纹样。 */
function hashPalette(key: string): StyleCoverSeed {
  let h = 0;
  for (let i = 0; i < key.length; i++) h = (h * 31 + key.charCodeAt(i)) | 0;
  const hue = Math.abs(h) % 360;
  const motifs: StyleCoverSeed["motif"][] = ["city", "sky", "ink", "toy", "film", "print", "sea", "court"];
  return {
    a: `hsl(${hue} 28% 10%)`,
    b: `hsl(${(hue + 28) % 360} 62% 52%)`,
    c: `hsl(${(hue + 48) % 360} 70% 72%)`,
    mark: key.slice(0, 10).toUpperCase(),
    motif: motifs[Math.abs(h) % motifs.length],
  };
}

/** dramaStylePoster 返回一张 SVG data URL。角标最多 18 个字符。value 去掉空白后当风格键，空的用 cover。label 有内容时当角标，否则用色板的 mark 或键，最多 18 个字符。 */
export function dramaStylePoster(value: string, label = "") {
  const key = String(value || "").trim() || "cover";
  const seed = STYLE_COVER_SEEDS[key] || hashPalette(key);
  const shown = escapeXml((label || seed.mark || key).slice(0, 18));
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 400" preserveAspectRatio="xMidYMid slice">
    <defs>
      <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0" stop-color="${seed.a}"/>
        <stop offset=".55" stop-color="${seed.b}"/>
        <stop offset="1" stop-color="${seed.c}"/>
      </linearGradient>
    </defs>
    <rect width="640" height="400" fill="url(#g)"/>
    ${MOTIFS[seed.motif]}
    <rect x="28" y="28" width="584" height="344" rx="18" fill="none" stroke="#fff" stroke-opacity=".16" stroke-width="2"/>
    <text x="40" y="318" fill="#fff" fill-opacity=".92" font-family="ui-sans-serif,system-ui,sans-serif" font-size="28" font-weight="700">${shown}</text>
    <text x="40" y="348" fill="#fff" fill-opacity=".55" font-family="ui-sans-serif,system-ui,sans-serif" font-size="13" letter-spacing="2">${escapeXml(key.toUpperCase())}</text>
  </svg>`)}`;
}
