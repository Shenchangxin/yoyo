func plat(id, zh, en, transport string, proactive bool, sumZh, sumEn string, fields ...Field) Platform {
	return Platform{
		ID: id, Transport: transport, Proactive: proactive,
		Name: Phrase{Zh: zh, En: en}, Summary: Phrase{Zh: sumZh, En: sumEn}, Fields: fields,
	}
}

func f(key, zh, en, helpZh, helpEn string, secret bool, def string) Field {
	return Field{Key: key, Label: Phrase{Zh: zh, En: en}, Help: Phrase{Zh: helpZh, En: helpEn}, Secret: secret, Default: def}
}

func specByID(id string) (Platform, bool) {
	for _, p := range Catalog() {
		if p.ID == id {
			return p, true
		}
	}
	return Platform{}, false
}
